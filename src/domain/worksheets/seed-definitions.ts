import type { FieldDefinition, FieldSchemaDocument, SeedDefinition } from './types.js'

function textField(
  key: string,
  label: string,
  options: Partial<FieldDefinition> = {},
): FieldDefinition {
  return {
    key,
    type: 'text',
    label,
    required: false,
    safetyRelevant: false,
    aiVisible: true,
    projected: false,
    maxLength: 500,
    ...options,
  }
}

function longtextField(
  key: string,
  label: string,
  options: Partial<FieldDefinition> = {},
): FieldDefinition {
  return {
    key,
    type: 'longtext',
    label,
    required: false,
    safetyRelevant: false,
    aiVisible: true,
    projected: false,
    maxLength: 4000,
    ...options,
  }
}

