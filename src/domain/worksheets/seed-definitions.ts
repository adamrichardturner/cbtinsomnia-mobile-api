const QUIZ_TOPICS = [
  'sleep need varies',
  'bed is for sleep',
  'clock watching',
  'catch-up sleep',
  'alcohol and sleep',
  'caffeine timing',
  'exercise timing',
  'naps',
  'worrying in bed',
  'sleep effort',
  'weekend lie-ins',
  'sleep quality vs quantity',
  'medication myths',
  'age and sleep',
  'blue light nuance',
  'wind-down value',
  'consistent rise time',
  'temporary sleepiness',
]

function quizFields(): FieldDefinition[] {
  const fields: FieldDefinition[] = []
  for (const [index, topic] of QUIZ_TOPICS.entries()) {
    const n = String(index + 1)
    fields.push(
      booleanField(`q${n}Answer`, `Item ${n}: ${topic}`, { required: true, projected: true }),
      longtextField(`q${n}Explanation`, `Explanation for item ${n}`, {
        required: false,
        aiVisible: true,
      }),
    )
  }
  return fields
}

