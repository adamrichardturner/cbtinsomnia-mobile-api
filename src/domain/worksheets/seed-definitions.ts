function scaleField(
  key: string,
  label: string,
  max: number,
  extras: Partial<FieldDefinition> = {},
): FieldDefinition {
  const points = []
  for (let value = 0; value <= max; value += 1) {
    points.push({ value, label: String(value) })
  }
  return {
    key,
    type: 'scale',
    label,
    required: false,
    safetyRelevant: false,
    aiVisible: true,
    projected: false,
    min: 0,
    max,
    points,
    ...extras,
  }
}

